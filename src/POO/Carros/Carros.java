package POO.Carros;

public class Carros {
    public String marca;
    public int ano;
    public String tipo;
    public String placa;
    public String motor;
    public String kilometraje;
    public String ciudad;
    public int puertas;



    public Carros(String marca, int ano, String tipo, String placa, String motor, String kilometraje, String ciudad, int puertas) {
        this.marca = marca;
        this.ano = ano;
        this.tipo = tipo;
        this.placa = placa;
        this.motor = motor;
        this.kilometraje = kilometraje;
        this.ciudad = ciudad;
        this.puertas = puertas;
    }







}